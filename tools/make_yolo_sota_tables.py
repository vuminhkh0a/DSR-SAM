#!/usr/bin/env python3
"""Append the YOLO-prompt SOTA segmentation tables to result_yolo.tex.

The tables use the ``*_yolov8x_seed<seed>`` rows in results.json, which are
produced by ``DG/sota/run_sota.py``.  Every row is looked up by its exact
results.json name (no fuzzy matching); the script fails loudly if a seed is
missing or an unexpected seed exists.

For each source domain there is one table with the two cross-domain targets:
    OTU    -> OVATUS, USOVA
    OVATUS -> OTU,    USOVA
    USOVA  -> OTU,    OVATUS

Values are mean +/- sample std (ddof=1) over seeds 42, 0, 100.  The best mean
per metric per target panel is bold (HD95: lowest is best).

Usage (from y_DG/):
    python3 tools/make_yolo_sota_tables.py
"""
import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS_PATH = ROOT / 'results.json'
TEX_PATH = ROOT / 'result_yolo.tex'

SEEDS = (42, 0, 100)
METRICS = ('dice', 'iou', 'precision', 'recall', 'hd95')
SOURCES = ('OTU', 'OVATUS', 'USOVA')
TARGETS_FOR = {
    'OTU': ('OVATUS', 'USOVA'),
    'OVATUS': ('OTU', 'USOVA'),
    'USOVA': ('OTU', 'OVATUS'),
}

# Method order mirrors the SOTA table in result_dsr_sam.tex.
TRAINABLE = (
    ('DeSAM', 'desam'),
    ('SR-SAM', 'sr_sam'),
    ('SAMed', 'sammed'),
    ('SAMUS', 'samus'),
    ('CoSAM', 'cosam'),
    ('MedSA', 'medsa'),
    ('BusSAM', 'bussam'),
    ('TransSAM', 'transsam'),
    ('MASAM', 'masam'),
)
ZERO_SHOT = (
    ('MedSAM', 'medsam'),
    ('SAM-Med2D', 'sammed2d'),
    ('UltraSAM', 'ultrasam'),
)

BEGIN_MARK = ('% === BEGIN YOLO SOTA TABLES '
              '(generated by tools/make_yolo_sota_tables.py) ===')
END_MARK = '% === END YOLO SOTA TABLES ==='


def load_entries():
    """Map exact prefix-stripped result name -> metric dict."""
    rows = json.loads(RESULTS_PATH.read_text())
    entries = {}
    for entry in rows:
        name = str(entry.get('name', ''))
        base = re.sub(r'^(?:gpu\d+|cpu)_', '', name)
        if base in entries:
            raise SystemExit(f'Duplicate result name after prefix strip: {base}')
        entries[base] = entry['results']
    return entries


def exact_name(token, source, target, seed, zero_shot=False):
    if zero_shot:
        return (f'vit_b_{token}_t_{target}_testonly'
                f'_yolov8x_seed{seed}')
    return (f'vit_b_{token}_s_{source}_t_{target}_best'
            f'_yolov8x_seed{seed}')


def seed_rows(entries, token, source, target, zero_shot=False):
    """Return the 3 seed result dicts, rejecting missing/extra seeds."""
    prefix = exact_name(token, source, target, '', zero_shot).rsplit('_seed', 1)[0]
    expected = {f'{prefix}_seed{s}' for s in SEEDS}
    actual = {name for name in entries if name.startswith(prefix + '_seed')}
    if actual != expected:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        raise SystemExit(
            f'Seed mismatch for {prefix}\n  missing: {missing}\n  extra: {extra}')
    return [entries[f'{prefix}_seed{seed}'] for seed in SEEDS]


def stats_for(entries, token, source, target, zero_shot=False):
    runs = seed_rows(entries, token, source, target, zero_shot)
    return {
        metric: (statistics.mean(run[metric] for run in runs),
                 statistics.stdev(run[metric] for run in runs))
        for metric in METRICS
    }


def fmt_cell(stats, metric):
    mean, std = stats[metric]
    return f'{mean:.2f} $\\pm$ {std:.2f}'


def build_table(source, entries):
    label = f'tab:yolo_sota_src_{source.lower()}'
    lines = [
        r'\begin{table}[t]',
        r'\centering',
        r'\small',
        (r'\caption{SOTA methods with YOLOv8x box prompts, source %s '
         r'(mean $\pm$ sample std over seeds 42, 0, 100). Best value per '
         r'metric per target is \textbf{bold}.}' % source),
        r'\label{%s}' % label,
        r'\begin{tabular}{lrrrrr}',
        r'\toprule',
        r'Method & Dice & IoU & Prec. & Rec. & HD95$\downarrow$ \\',
        r'\midrule',
    ]

    for target in TARGETS_FOR[source]:
        rows = []   # (display name, stats)
        for display, token in TRAINABLE:
            rows.append((display, stats_for(entries, token, source, target)))
        zero_rows = [(display, stats_for(entries, token, source, target,
                                         zero_shot=True))
                     for display, token in ZERO_SHOT]

        all_rows = rows + zero_rows
        best = {
            metric: (min if metric == 'hd95' else max)(
                stats[metric][0] for _, stats in all_rows)
            for metric in METRICS
        }

        def emit(display, stats):
            cells = []
            for metric in METRICS:
                body = fmt_cell(stats, metric)
                if abs(stats[metric][0] - best[metric]) < 1e-9:
                    body = f'\\textbf{{{body}}}'
                cells.append(body)
            lines.append(' & '.join([display, *cells]) + r' \\')

        lines.append(r'\multicolumn{6}{l}{\textit{Target: %s}} \\' % target)
        lines.append(r'\midrule')
        lines.append(r'\multicolumn{6}{l}{\textit{SAM-based DG methods}} \\')
        for display, stats in rows:
            emit(display, stats)
        lines.append(r'\addlinespace[2pt]')
        lines.append(r'\multicolumn{6}{l}{\textit{Zero-shot foundation models}} \\')
        for display, stats in zero_rows:
            emit(display, stats)
        lines.append(r'\addlinespace[4pt]')

    lines += [
        r'\bottomrule',
        r'\end{tabular}',
        r'\end{table}',
    ]
    return lines


def build_block(entries):
    lines = [BEGIN_MARK, '']
    for source in SOURCES:
        lines.extend(build_table(source, entries))
        lines.append('')
    lines.append(END_MARK)
    return '\n'.join(lines) + '\n'


def main():
    entries = load_entries()
    block = build_block(entries)

    text = TEX_PATH.read_text()
    if BEGIN_MARK in text:
        before, rest = text.split(BEGIN_MARK, 1)
        _, after = rest.split(END_MARK, 1)
        text = before + block + '\n' + after.lstrip('\n')
    else:
        marker = '\\end{document}'
        cut = text.rindex(marker)
        text = text[:cut] + block + '\n' + text[cut:]
    TEX_PATH.write_text(text)
    print(f'Updated {TEX_PATH.name}: 3 SOTA tables, '
          f'{len(TRAINABLE) + len(ZERO_SHOT)} methods/panel.')


if __name__ == '__main__':
    main()
