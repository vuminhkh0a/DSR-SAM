#!/usr/bin/env python3
"""Append the DSR-SAM2 ablation table to result_yolo.tex.

The study is the one run by ``DG/sota/run_sota.py``:
    source OTU -> OVATUS, USOVA; seeds 42, 0, 100; YOLOv8x box prompts.
    results.json names:
        vit_b_dsr_sam2_ab_<tag>_sam_s_OTU_t_<target>_best_yolov8x_seed<seed>

Every row is looked up by its exact results.json name (no fuzzy matching);
the script fails if a seed is missing or an unexpected seed exists.
Values are mean +/- sample std (ddof=1); the best mean per metric per target
panel is bold (HD95: lowest is best).

Usage (from y_DG/):
    python3 tools/make_yolo_ablation_table.py
"""
import json
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tools.make_ablation_table import ABLATIONS, FLAGS, LABELS

RESULTS_PATH = ROOT / 'results.json'
TEX_PATH = ROOT / 'result_yolo.tex'

SEEDS = (42, 0, 100)
METRICS = ('dice', 'iou', 'precision', 'recall', 'hd95')
SOURCE = 'OTU'
TARGETS = ('OVATUS', 'USOVA')

BEGIN_MARK = ('% === BEGIN YOLO DSR-SAM2 ABLATION TABLE '
              '(generated by tools/make_yolo_ablation_table.py) ===')
END_MARK = '% === END YOLO DSR-SAM2 ABLATION TABLE ==='


def load_entries():
    """Map exact prefix-stripped results name -> metric dict."""
    rows = json.loads(RESULTS_PATH.read_text())
    entries = {}
    for entry in rows:
        name = str(entry.get('name', ''))
        base = re.sub(r'^(?:gpu\d+|cpu)_', '', name)
        if base in entries:
            raise SystemExit(f'Duplicate result name after prefix strip: {base}')
        entries[base] = entry['results']
    return entries


def name_for(tag, target, seed):
    return (f'vit_b_dsr_sam2_ab_{tag}_sam_s_{SOURCE}_t_{target}_best'
            f'_yolov8x_seed{seed}')


def seed_rows(entries, tag, target):
    prefix = (f'vit_b_dsr_sam2_ab_{tag}_sam_s_{SOURCE}_t_{target}_best'
              f'_yolov8x_seed')
    expected = {f'{prefix}{seed}' for seed in SEEDS}
    actual = {name for name in entries if name.startswith(prefix)}
    if actual != expected:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        raise SystemExit(
            f'Seed mismatch for {tag} | {target}\n'
            f'  missing: {missing}\n  extra: {extra}')
    return [entries[f'{prefix}{seed}'] for seed in SEEDS]


def stats_for(entries, tag, target):
    runs = seed_rows(entries, tag, target)
    return {
        metric: (statistics.mean(run[metric] for run in runs),
                 statistics.stdev(run[metric] for run in runs))
        for metric in METRICS
    }


def fmt_cell(stats, metric):
    mean, std = stats[metric]
    return f'{mean:.2f} $\\pm$ {std:.2f}'


def build_table(entries):
    lines = [
        r'\begin{table}[t]',
        r'\centering',
        r'\scriptsize',
        r'\setlength{\tabcolsep}{2pt}',
        (r'\caption{DSR-SAM2 ablation study with YOLOv8x box prompts on '
         r'source OTU (CBA $n=8$, gate width $C=768$; mean $\pm$ sample std '
         r'over seeds 42, 0, 100). Best value per metric per target is '
         r'\textbf{bold}.}'),
        r'\label{tab:yolo_dsr_sam2_ablation}',
        r'\begin{tabular}{lccccc rrrrr}',
        r'\toprule',
        r'& \multicolumn{5}{c}{Configuration} & '
        r'\multicolumn{5}{c}{Metrics} \\',
        r'\cmidrule(lr){2-6}\cmidrule(lr){7-11}',
        r'Variant & CNN & CBA & Gate & CKA & $L_{\mathrm{CKA}}$ & '
        r'Dice & IoU & Prec. & Rec. & HD95$\downarrow$ \\',
        r'\midrule',
    ]

    stats = {(tag, target): stats_for(entries, tag, target)
             for tag, *_ in ABLATIONS for target in TARGETS}

    for target in TARGETS:
        best = {
            metric: (min if metric == 'hd95' else max)(
                stats[(tag, target)][metric][0] for tag, *_ in ABLATIONS)
            for metric in METRICS
        }
        lines.append(r'\multicolumn{11}{l}{\textit{Target: %s}} \\' % target)
        lines.append(r'\midrule')
        for tag, *_ in ABLATIONS:
            cells = []
            for metric in METRICS:
                body = fmt_cell(stats[(tag, target)], metric)
                if abs(stats[(tag, target)][metric][0] - best[metric]) < 1e-9:
                    body = f'\\textbf{{{body}}}'
                cells.append(body)
            lines.append(' & '.join([LABELS[tag], *FLAGS[tag], *cells]) + r' \\')
        lines.append(r'\addlinespace[4pt]')

    lines += [
        r'\bottomrule',
        r'\end{tabular}',
        r'\end{table}',
    ]
    return lines


def main():
    entries = load_entries()
    block = '\n'.join([BEGIN_MARK, ''] + build_table(entries)
                      + ['', END_MARK]) + '\n'

    text = TEX_PATH.read_text()
    if BEGIN_MARK in text:
        before, rest = text.split(BEGIN_MARK, 1)
        _, after = rest.split(END_MARK, 1)
        text = before + block + '\n' + after.lstrip('\n')
    else:
        marker = '\\end{document}'
        cut = text.rindex(marker)
        text = text[:cut] + block + '\n' + text[cut:]
    TEX_PATH.write_text(text)
    print(f'Updated {TEX_PATH.name}: DSR-SAM2 ablation, '
          f'{len(ABLATIONS)} variants x {len(TARGETS)} targets.')


if __name__ == '__main__':
    main()
